const mongoose = require("mongoose");

const systemAdminSchema = new mongoose.Schema(
    {
        name: {
            type: String,
            required: true
        },

        email: {
            type: String,
            required: true,
            unique: true
        },

        password: {
            type: String,
            required: true
        },

        role: {
            type: String,
            default: "SYSTEM_ADMIN"
        },

        status: {
            type: String,
            enum: ["ACTIVE", "INACTIVE"],
            default: "ACTIVE"
        }
    },
    {
        timestamps: true
    });

module.exports = mongoose.model(
    "SystemAdmin",
    systemAdminSchema
);